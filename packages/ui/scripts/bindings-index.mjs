// Writes src/engine/types.ts: one re-export per generated binding.
import { readdirSync, writeFileSync } from "node:fs";

const dir = new URL("../src/engine/bindings/", import.meta.url);
const names = readdirSync(dir).filter((f) => f.endsWith(".ts")).map((f) => f.slice(0, -3)).sort();
const lines = names.map((n) => `export type { ${n} } from "./bindings/${n}";`);
writeFileSync(new URL("../src/engine/types.ts", import.meta.url), `// Generated by scripts/bindings-index.mjs.\n${lines.join("\n")}\n`);
